// האם נקודה על יבשה (לא כולל אגמים)
GEO.isLand = function (lat, lon) {
  if (lat < -69) return true;                     // אנטארקטיקה
  for (var i = 0; i < GEO.CONTINENTS.length; i++) {
    if (U.pointInPoly(lon, lat, GEO.CONTINENTS[i].poly)) return true;
  }
  return false;
};

// האם נקודה בתוך אגם — מחזיר את האגם או null
GEO.inLake = function (lat, lon) {
  for (var i = 0; i < GEO.LAKES.length; i++) {
    if (U.pointInPoly(lon, lat, GEO.LAKES[i].poly)) return GEO.LAKES[i];
  }
  return null;
};

GEO.inIsrael = function (lat, lon) {
  var b = GEO.ISRAEL_BOUNDS;
  return lat >= b.latMin && lat <= b.latMax && lon >= b.lonMin && lon <= b.lonMax;
};

// המדינה/היבשת הקרובה ביותר לתווית מיקום
GEO.nearestCountry = function (lat, lon) {
  var best = null, bestD = 1e9;
  for (var i = 0; i < GEO.COUNTRIES.length; i++) {
    var c = GEO.COUNTRIES[i];
    var d = U.distKm(lat, lon, c.lat, c.lon);
    if (d < bestD) { bestD = d; best = c; }
  }
  return { country: best, distKm: bestD };
};

// העיר הקרובה ביותר (ישראל + עולם)
GEO.nearestCity = function (lat, lon, maxKm) {
  var best = null, bestD = maxKm || 60;
  var lists = [GEO.ISRAEL_CITIES, GEO.WORLD_CITIES];
  for (var L = 0; L < lists.length; L++) {
    for (var i = 0; i < lists[L].length; i++) {
      var c = lists[L][i];
      var d = U.distKm(lat, lon, c.lat, c.lon);
      if (d < bestD) { bestD = d; best = c; }
    }
  }
  return best ? { city: best, distKm: bestD } : null;
};
